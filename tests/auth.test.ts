test('partial question changes preserve shared source material and student progress is private',async t=>{
  const root=mkdtempSync(join(tmpdir(),'zhixu-question-patch-')),c=buildApp(new Store(root));
  await c.app.ready();t.after(async()=>{await c.app.close();rmSync(root,{recursive:true,force:true});});
  const send=(url:string,method:any='GET',payload?:any,cookie?:string)=>c.app.inject({url:'/api'+url,method,payload,headers:{host:'127.0.0.1:4317',...(cookie?{cookie}:{})}});
  const password='patch-test-password-123';
  const setup=await send('/auth/setup','POST',{username:'owner',password,name:'Owner'});
  const admin=String(setup.headers['set-cookie']).split(';')[0];
  const invite=(await send('/auth/invites','POST',{uses:2},admin)).json().code;
  const alice=await send('/auth/register','POST',{username:'alice',password,name:'Alice',invite});
  const student=String(alice.headers['set-cookie']).split(';')[0];
  const folder=(await send('/folders','POST',{name:'原始资料'},admin)).json();
  const image=c.store.attach(Buffer.from('test image'),'source.png','image/png');
  const input={title:'保留选项、答案和来源',stem:'选择正确的结论',type:'多选',subject:'线性代数',options:['A. 结论一','B. 结论二'],answer:'AB',answerConfirmed:true,answerOrigin:'人工',explanation:'已核对解释',subquestions:['说明理由'],folderId:folder.id,materialKind:'page',sources:[{attachmentId:image.id,imageId:image.id,name:'原始资料',page:3}]};
  const created=await send('/questions','POST',input,admin);assert.equal(created.statusCode,200,created.body);
  const q=created.json();
  for(const cookie of [student,admin]){
    const response=await send('/questions/'+q.id,'PATCH',{wrong:true,mastered:false},cookie);
    assert.equal(response.statusCode,200,response.body);
    const actual=response.json();for(const [key,value] of Object.entries(input))assert.deepEqual(actual[key],value,key);
  }
  assert.equal((await send('/questions/'+q.id,'GET',undefined,student)).json().question.wrong,true);
  assert.equal(c.store.get<any>('questions',q.id)?.wrong,false);
  const renamed=await send('/questions/'+q.id,'PATCH',{title:'修改标题'},admin);
  assert.equal(renamed.json().folderId,folder.id);assert.deepEqual(renamed.json().sources,input.sources);assert.equal(renamed.json().answer,'AB');
  const cleared=await send('/questions/'+q.id,'PATCH',{folderId:null,sources:[],options:[],answer:'',answerConfirmed:false},admin);
  assert.equal(cleared.statusCode,200,cleared.body);assert.equal(cleared.json().folderId,null);assert.deepEqual(cleared.json().sources,[]);assert.equal(cleared.json().answer,'');assert.equal(cleared.json().subject,'线性代数');
});

test('public setup blocked, invitation registration, role restrictions, personal records and backup isolation',async t=>{
  const root=mkdtempSync(join(tmpdir(),'zhixu-auth-')),c=buildApp(new Store(root),{publicOrigin:'https://study.example:8443'});
  await c.app.ready();t.after(async()=>{await c.app.close();rmSync(root,{recursive:true,force:true});});
  const send=(url:string,method:any='GET',payload?:any,cookie?:string,host='127.0.0.1:4317',origin?:string)=>c.app.inject({url:'/api'+url,method,payload,headers:{host,...(cookie?{cookie}:{}),...(origin?{origin}:{})}});
  const login={username:'owner',password:'a-test-password-123',name:'站长'};
  assert.equal((await send('/bootstrap')).statusCode,401);
  assert.equal((await c.app.inject({url:'/api/auth/status',headers:{host:'study.example:8443','sec-fetch-site':'cross-site'}})).statusCode,200);
  assert.equal((await c.app.inject({url:'/api/auth/login',method:'POST',payload:login,headers:{host:'study.example:8443','sec-fetch-site':'cross-site'}})).statusCode,403);
  assert.equal((await send('/auth/setup','POST',login,undefined,'study.example:8443')).statusCode,403);
  assert.equal((await send('/auth/setup','POST',login,undefined,undefined,'https://evil.example')).statusCode,403);
  const owner=await send('/auth/setup','POST',login);assert.equal(owner.statusCode,200,owner.body);
  const admin=String(owner.headers['set-cookie']).split(';')[0];
  assert.match(String(owner.headers['set-cookie']),/HttpOnly/);
  assert.equal((await send('/auth/setup','POST',login)).statusCode,409);
  const invitation=(await send('/auth/invites','POST',{uses:2},admin)).json().code;
  const reg=async(username:string)=>{const r=await send('/auth/register','POST',{username,password:login.password,name:username,invite:invitation},undefined,'study.example:8443');assert.equal(r.statusCode,200,r.body);assert.match(String(r.headers['set-cookie']),/Secure/);return String(r.headers['set-cookie']).split(';')[0];};
  const a=await reg('alice'),b=await reg('bob');
  assert.equal((await send('/auth/register','POST',{...login,username:'extra',invite:invitation})).statusCode,400);
  for(const [url,method,body] of [['/settings','GET',undefined],['/backup','GET',undefined],['/questions','POST',{title:'x',stem:'x'}],['/auth/invites','POST',{}]] as const)assert.equal((await send(url,method,body,a)).statusCode,403,url);
  const q=(await send('/questions','POST',{title:'求导',stem:'求 $x^2$ 的导数。'},admin)).json();
  assert.equal((await send('/questions/'+q.id,'PATCH',{stem:'changed'},a)).statusCode,403);
  await send('/questions/'+q.id,'PATCH',{wrong:true},a);
  assert.equal((await send('/bootstrap','GET',undefined,a)).json().stats.wrong,1);
  assert.equal((await send('/bootstrap','GET',undefined,b)).json().stats.wrong,0);
  const attempts=await Promise.all([send(`/questions/${q.id}/attempts`,'POST',{answer:'alice answer'},a),send(`/questions/${q.id}/attempts`,'POST',{answer:'bob answer'},b)]);
  const aliceAttempt=attempts[0].json();
  const calls:any[]=[];
  const ai=createServer(async(req,res)=>{let text='';for await(const part of req)text+=part;const body=JSON.parse(text);calls.push(body);res.setHeader('Content-Type','application/json');res.end(JSON.stringify({choices:[{message:{content:body.messages[0].content.includes('输出 JSON')?JSON.stringify({correct:true,feedback:'步骤核对完成。'}):'求导结果为 $2x$。'}}]}));});
  await new Promise<void>(r=>ai.listen(0,'127.0.0.1',r));t.after(()=>new Promise<void>(r=>ai.close(()=>r())));
  c.store.saveConfig({baseUrl:`http://127.0.0.1:${(ai.address() as any).port}/v1`,model:'global:deepseek-v4.1-flash',visionModel:'global:deepseek-v4.1-flash',key:'test-only-key'});
  assert.equal((await send('/attempts/'+aliceAttempt.id+'/grade','POST',{},a)).statusCode,200);
  assert.equal((await send('/questions/'+q.id+'/explanations','POST',{},a)).statusCode,200);
  assert.equal(calls.length,2);assert.ok(calls.every(body=>body.model==='global:deepseek-v4.1-flash'));
  assert.equal((await send('/questions/'+q.id,'GET',undefined,b)).json().explanations.length,0);
  assert.equal((await send('/attempts/'+aliceAttempt.id,'PATCH',{correct:true},b)).statusCode,404);
  assert.deepEqual((await send('/bootstrap','GET',undefined,a)).json().attempts.map((r:any)=>r.answer),['alice answer']);
  const aliceUser=c.auth!.db.prepare("SELECT id FROM users WHERE username='alice'").get() as any;
  const photo=c.store.asUser({...aliceUser,username:'alice',name:'alice',role:'student'},()=>c.store.attach(Buffer.from('private'),'private.png','image/png'));
  assert.equal((await send('/attachments/'+photo.id,'GET',undefined,b)).statusCode,404);
  assert.equal((await send('/attachments/'+photo.id,'GET',undefined,admin)).statusCode,404);
  const backup=c.store.asUser(owner.json().user,()=>makeBackup(c.store));
  c.store.asUser(owner.json().user,()=>restoreBackup(c.store,backup));
  const own=(await send('/bootstrap','GET',undefined,a)).json();assert.equal(own.stats.wrong,1);assert.equal(own.attempts.length,1);
  const photoRecord=c.store.all<any>('attachments').find(p=>p.name==='private.png');
  assert.equal(photoRecord.ownerId,aliceUser.id);
  assert.equal((await send('/attachments/'+photoRecord.id,'GET',undefined,a)).statusCode,200);
  assert.equal((await send('/attachments/'+photoRecord.id,'GET',undefined,b)).statusCode,404);
  await send('/auth/password','POST',{current:login.password,password:'replacement-password-456'},a);
  assert.equal((await send('/bootstrap','GET',undefined,a)).statusCode,401);
  const fresh=await send('/auth/login','POST',{username:'alice',password:'replacement-password-456'});assert.equal(fresh.statusCode,200);
  await send('/auth/users/'+aliceUser.id,'PATCH',{disabled:true},admin);
  assert.equal((await send('/bootstrap','GET',undefined,String(fresh.headers['set-cookie']).split(';')[0])).statusCode,401);
});
